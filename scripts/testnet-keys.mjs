// BSC testnet only: create fresh test keys in the gitignored .env.deploy, under TESTNET_* names, and
// print their ADDRESSES (never the keys). Keys that already exist are kept. The mainnet slots in the
// same file (DEPLOYER_PRIVATE_KEY, …) are not read or changed.
// Usage: node scripts/testnet-keys.mjs
import fs from "node:fs";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const FILE = new URL("../.env.deploy", import.meta.url);
const ROLES = ["DEPLOYER", "SIGNER", "RELAYER", ...Array.from({ length: 12 }, (_, i) => `ATTACKER${i + 1}`), "NONHOLDER", "SIGNER2", "NEWOWNER"];
const have = new Map();
if (fs.existsSync(FILE)) {
  for (const line of fs.readFileSync(FILE, "utf8").split("\n")) {
    const m = /^TESTNET_([A-Z0-9]+)_PRIVATE_KEY=(0x[0-9a-fA-F]{64})\s*$/.exec(line);
    if (m) have.set(m[1], m[2]);
  }
}
const add = [];
for (const r of ROLES) if (!have.has(r)) { const k = generatePrivateKey(); have.set(r, k); add.push(`TESTNET_${r}_PRIVATE_KEY=${k}`); }
if (add.length) {
  const head = fs.existsSync(FILE) && !fs.readFileSync(FILE, "utf8").includes("# --- BSC testnet") ? "\n# --- BSC testnet (chain 97) test keys: worthless, generated by scripts/testnet-keys.mjs ---\n" : fs.existsSync(FILE) ? "" : "# --- BSC testnet (chain 97) test keys: worthless, generated by scripts/testnet-keys.mjs ---\n";
  fs.appendFileSync(FILE, head + add.join("\n") + "\n", { mode: 0o600 });
  fs.chmodSync(FILE, 0o600);
}
console.log(JSON.stringify({ created: add.length, file: ".env.deploy", addresses: Object.fromEntries(ROLES.map((r) => [r.toLowerCase(), privateKeyToAccount(have.get(r)).address])) }, null, 2));
